SELECT DISTINCT p.PNAME 
FROM PARTS p
INNER JOIN CATALOG c ON p.PID = c.PID;

SELECT s.SNAME 
FROM SUPPLIERS s
JOIN CATALOG c ON s.SID = c.SID
GROUP BY s.SID, s.SNAME
HAVING COUNT(DISTINCT c.PID) = (SELECT COUNT(*) FROM PARTS);

SELECT s.SNAME 
FROM SUPPLIERS s 
WHERE NOT EXISTS (
    SELECT p.PID FROM PARTS p WHERE p.COLOR = 'Red'
    AND NOT EXISTS (
        SELECT c.PID FROM CATALOG c WHERE c.SID = s.SID AND c.PID = p.PID
    )
);

SELECT p.PNAME, p.PID 
FROM PARTS p
WHERE EXISTS (
    SELECT 1 FROM CATALOG c 
    INNER JOIN SUPPLIERS s ON c.SID = s.SID 
    WHERE c.PID = p.PID AND s.SNAME = 'Acme Widget'
)
AND NOT EXISTS (
    SELECT 1 FROM CATALOG c2 
    INNER JOIN SUPPLIERS s2 ON c2.SID = s2.SID 
    WHERE c2.PID = p.PID AND s2.SNAME = 'Acme Widget'
);

WITH AvgPartCost AS (
    SELECT PID, AVG(COST) AS AvgCost 
    FROM CATALOG 
    GROUP BY PID
)
SELECT DISTINCT c.SID 
FROM CATALOG c
INNER JOIN AvgPartCost a ON c.PID = a.PID
WHERE c.COST > a.AvgCost;

SELECT c.PID, s.SNAME 
FROM CATALOG c
INNER JOIN SUPPLIERS s ON c.SID = s.SID
WHERE c.COST >= ALL (
    SELECT COST FROM CATALOG c2 WHERE c2.PID = c.PID
);

SELECT s.SNAME, p.PNAME 
FROM CATALOG c
JOIN SUPPLIERS s ON c.SID = s.SID
JOIN PARTS p ON c.PID = p.PID
WHERE c.COST = (SELECT MAX(COST) FROM CATALOG);

SELECT s.SNAME 
FROM SUPPLIERS s
WHERE NOT EXISTS (
    SELECT 1 FROM CATALOG c
    JOIN PARTS p ON c.PID = p.PID
    WHERE c.SID = s.SID AND p.COLOR = 'Red'
);

SELECT s.SNAME, SUM(c.COST) AS Total_Cost
FROM SUPPLIERS s
INNER JOIN CATALOG c USING (SID)
GROUP BY s.SID, s.SNAME;

SELECT SID, SNAME FROM (
    SELECT s.SID, s.SNAME, COUNT(c.PID) as part_count
    FROM SUPPLIERS s
    INNER JOIN CATALOG c ON s.SID = c.SID
    WHERE c.COST < 20
    GROUP BY s.SID, s.SNAME
) tbl
WHERE part_count >= 2;

SELECT c.PID, p.PNAME, s.SNAME, c.COST 
FROM CATALOG c
JOIN PARTS p ON c.PID = p.PID
JOIN SUPPLIERS s ON c.SID = s.SID
WHERE c.COST <= ALL (
    SELECT COST FROM CATALOG c2 WHERE c2.PID = c.PID
);

CREATE VIEW most_expensive_supplier_per_part AS
WITH RankedCatalog AS (
    SELECT c.PID, p.PNAME, s.SID, s.SNAME, c.COST,
           RANK() OVER(PARTITION BY c.PID ORDER BY c.COST DESC) as cost_rank
    FROM CATALOG c
    JOIN PARTS p ON c.PID = p.PID
    JOIN SUPPLIERS s ON c.SID = s.SID
)
SELECT PID, PNAME, SID, SNAME, COST 
FROM RankedCatalog 
WHERE cost_rank = 1;